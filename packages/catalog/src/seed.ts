export const featuredIds = ["monstera", "zz", "calathea", "snake", "fiddle", "orchid", "pothos", "bonsai"];

// Sample opening stock. A couple of sizes start low or sold out so those states are visible.
const stockOverrides: Record<string, Partial<Record<SizeId, number>>> = {
  fiddle: { S: 0, M: 4 },
  bonsai: { S: 3 },
  topiary: { M: 0 },
  orchid: { L: 2 },
};

function buildVariants(r: RawProduct): Variant[] {
  return SIZES.map((size) => ({
    size,
    price: suggestedPrice(r.price, r.size, size),
    compareAt: size === r.size ? r.compareAt : undefined,
    stock: stockOverrides[r.id]?.[size] ?? 24,
    lowStockThreshold: 5,
    sku: `VN-${r.id.toUpperCase()}-${size}`,
    active: true,
  }));
}

export const seedProducts: Product[] = rawProducts.map((r, i) => {
  const variants = buildVariants(r);
  const url = unsplash(r.image);
  return {
    ...r,
    ...listingPrice(variants, r.size),
    status: "published",
    image: url,
    imageFocal: "50% 50%",
    images: [{ url, alt: r.name, focalX: 0.5, focalY: 0.5 }],
    variants,
    details: rawDetails[r.id],
    featured: featuredIds.includes(r.id),
    sortOrder: featuredIds.includes(r.id) ? featuredIds.indexOf(r.id) : 100 + i,
  };
});

