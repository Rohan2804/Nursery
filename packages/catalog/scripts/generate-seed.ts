// Generates supabase/seed.sql from the built-in catalog. Run: npm run db:seed-sql
// Inserts are "on conflict do nothing", so re-running never overwrites edits made in the admin.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { seedCollections, seedPlanters, seedProducts } from "../src/seed.ts";

const q = (v: unknown): string => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number") return String(v);
  if (typeof v === "boolean") return v ? "true" : "false";
  if (Array.isArray(v)) return `array[${v.map(q).join(",")}]::text[]`;
  return `'${String(v).replace(/'/g, "''")}'`;
};

const lines: string[] = ["-- Generated by packages/catalog/scripts/generate-seed.ts — do not edit by hand.", "begin;", ""];

for (const p of seedPlanters) {
  lines.push(
    `insert into public.planters (id, label, note, price, swatch, sort_order) values (${[p.id, p.label, p.note, p.price, p.swatch, seedPlanters.indexOf(p)].map(q).join(", ")}) on conflict (id) do nothing;`,
  );
}
lines.push("");

for (const p of seedProducts) {
  const d = p.details;
  lines.push(
    `insert into public.plants (slug, name, botanical, blurb, badge, status, light, space, pet_safe, care, natural_size, rating, review_count, water, water_level, humidity, humidity_level, temperature, origin, grower_note, featured, sort_order) values (${[
      p.id, p.name, p.botanical, p.blurb, p.badge ?? null, "published", p.light, p.space, p.petSafe, p.care, p.size, p.rating, p.reviews,
      d.water, d.waterLevel, d.humidity, d.humidityLevel, d.temperature, d.origin, d.growerNote, p.featured, p.sortOrder,
    ].map(q).join(", ")}) on conflict (slug) do nothing;`,
  );
  for (const v of p.variants) {
    lines.push(
      `insert into public.plant_variants (plant_id, size, price, compare_at, stock, low_stock_threshold, sku, active) select id, ${[v.size, v.price, v.compareAt ?? null, v.stock, v.lowStockThreshold, v.sku, v.active].map(q).join(", ")} from public.plants where slug = ${q(p.id)} on conflict (plant_id, size) do nothing;`,
    );
  }
  for (const [i, img] of p.images.entries()) {
    lines.push(
      `insert into public.plant_images (plant_id, url, alt, position, focal_x, focal_y) select id, ${[img.url, img.alt, i, img.focalX, img.focalY].map(q).join(", ")} from public.plants where slug = ${q(p.id)} and not exists (select 1 from public.plant_images i join public.plants pl on pl.id = i.plant_id where pl.slug = ${q(p.id)});`,
    );
  }
  lines.push("");
}

for (const c of seedCollections) {
  lines.push(
    `insert into public.collections (slug, grp, title, short, description, intro, image_url, rules, status, sort_order) values (${[c.slug, c.group, c.title, c.short, c.description, c.intro, c.image].map(q).join(", ")}, ${q(JSON.stringify(c.rules))}::jsonb, 'published', ${c.sortOrder}) on conflict (slug) do nothing;`,
  );
}

lines.push("", "commit;", "");
const out = fileURLToPath(new URL("../../../supabase/seed.sql", import.meta.url));
writeFileSync(out, lines.join("\n"));
console.log(`Wrote ${out}: ${seedProducts.length} plants, ${seedCollections.length} collections, ${seedPlanters.length} planters`);
